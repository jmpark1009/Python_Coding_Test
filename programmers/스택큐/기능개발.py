# 스택큐/기능개발

def solution(progresses, speeds):
    # -------------------------------------------------------------
    # 1. 초기 변수 선언
    # - answer: 각 배포 차수별 배포 기능 개수를 담을 빈 리스트
    # - days: 각 기능별 완료까지 소요되는 일수를 담을 빈 리스트
    # -------------------------------------------------------------
    answer = []
    days = []

    # -------------------------------------------------------------
    # 2. 각 기능의 완료 소요 일수(days) 계산
    # - range(len(progresses))로 인덱스 순회
    # - 남은 작업량: 100 - progresses[i]
    # - 올림 공식: (남은 작업량 + 속도 - 1) // 속도
    # - 계산된 일수를 days에 append
    # -------------------------------------------------------------
    for i in range(len(progresses)):
        days.append((100 - progresses[i] + speeds[i] - 1) // speeds[i])
    print(days)

    # -------------------------------------------------------------
    # 3. 배포 기준일(current) 및 배포 수량(count) 초기화
    # - current: 첫 번째 작업의 완료 일수 (days[0])
    # - count: 현재 기준일에 함께 배포될 기능 수 (1로 시작)
    # -------------------------------------------------------------
    current = days[0]
    count = 1
    
    # -------------------------------------------------------------
    # 4. 두 번째 작업부터 순회하며 배포 묶음(Group) 판별
    # - range(1, len(days))로 순회
    # - [조건 1] days[i] <= current:
    #            현재 기준일 내에 완료되므로 함께 배포 가능 -> count 1 증가
    # - [조건 2] days[i] > current (else):
    #            새로운 배포 차수 시작!
    #            1) 직전까지 모인 count를 answer에 append
    #            2) count를 1로 리셋
    #            3) current를 현재 작업의 소요 일수(days[i])로 갱신
    # -------------------------------------------------------------
    for i in range(1, len(days)):
        if days[i] <= current:
            count += 1
        else:
            answer.append(count)
            count = 1
            current = days[i]

    # -------------------------------------------------------------
    # 5. 마무리 배포 처리 및 반환
    # - 루프가 끝난 후 마지막 그룹의 count를 answer에 append
    # - answer 반환
    # -------------------------------------------------------------
    answer.append(count)
    return answer
